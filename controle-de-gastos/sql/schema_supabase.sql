create table if not exists public.gastos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data text not null, descricao text not null, categoria text not null,
  pagamento text not null, valor numeric(10,2) not null check (valor > 0),
  criado_em timestamptz not null default now()
);
create table if not exists public.receitas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  data text not null, descricao text not null, fonte text not null,
  valor numeric(10,2) not null check (valor > 0),
  criado_em timestamptz not null default now()
);
create table if not exists public.categorias (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nome text not null, tipo text not null check (tipo in ('gasto','receita')),
  ativa boolean not null default true, unique(user_id, nome, tipo)
);
create table if not exists public.orcamento_categoria (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  mes char(7) not null, categoria text not null, valor numeric(10,2) not null check (valor > 0),
  alerta numeric(4,2) not null default .80 check (alerta between .01 and .99),
  unique(user_id, mes, categoria)
);
create table if not exists public.orcamento_global (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references auth.users(id) on delete cascade,
  valor numeric(10,2) not null check (valor > 0),
  alerta numeric(4,2) not null default .80 check (alerta between .01 and .99),
  atualizado_em timestamptz not null default now()
);
create table if not exists public.recorrencias (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  descricao text not null, valor numeric(10,2) not null check (valor > 0), categoria text not null,
  pagamento text not null, data_inicio text not null, data_fim text,
  frequencia text not null check (frequencia in ('semanal','mensal','anual')),
  status text not null default 'ativa' check (status in ('ativa','pausada','encerrada'))
);
create table if not exists public.metas (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  nome text not null, valor_desejado numeric(10,2) not null check (valor_desejado > 0),
  valor_inicial numeric(10,2) not null default 0 check (valor_inicial >= 0), prazo text,
  status text not null default 'ativa' check (status in ('ativa','concluida','arquivada'))
);
create table if not exists public.meta_movimentos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  meta_id bigint not null references public.metas(id) on delete cascade,
  tipo text not null check (tipo in ('aporte','retirada')), valor numeric(10,2) not null check (valor > 0),
  descricao text not null default '', data text not null
);

create index if not exists gastos_user_data on public.gastos(user_id, data);
create index if not exists receitas_user_data on public.receitas(user_id, data);
create index if not exists metas_user_status on public.metas(user_id, status);

alter table public.gastos enable row level security;
alter table public.receitas enable row level security;
alter table public.categorias enable row level security;
alter table public.orcamento_categoria enable row level security;
alter table public.orcamento_global enable row level security;
alter table public.recorrencias enable row level security;
alter table public.metas enable row level security;
alter table public.meta_movimentos enable row level security;

do $$ declare tabela text; begin
  foreach tabela in array array['gastos','receitas','categorias','orcamento_categoria','orcamento_global','recorrencias','metas','meta_movimentos'] loop
    execute format('drop policy if exists %I_user_policy on public.%I', tabela, tabela);
    execute format('create policy %I_user_policy on public.%I for all using (user_id = auth.uid()) with check (user_id = auth.uid())', tabela, tabela);
  end loop;
end $$;

-- Um movimento só pode apontar para uma meta do mesmo usuário.
drop policy if exists meta_movimentos_user_policy on public.meta_movimentos;
create policy meta_movimentos_user_policy on public.meta_movimentos
  for all
  using (
    user_id = auth.uid()
    and exists (
      select 1 from public.metas
      where metas.id = meta_movimentos.meta_id
        and metas.user_id = auth.uid()
    )
  )
  with check (
    user_id = auth.uid()
    and exists (
      select 1 from public.metas
      where metas.id = meta_movimentos.meta_id
        and metas.user_id = auth.uid()
    )
  );
